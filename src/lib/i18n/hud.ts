function overlay(locale: Partial<HudCopy>): HudCopy {
  return {
    jump: { ...en.jump, ...locale.jump },
    mode: { ...en.mode, ...locale.mode },
    chrome: { ...en.chrome, ...locale.chrome },
    learning: { ...en.learning, ...locale.learning },
    blackbox: { ...en.blackbox, ...locale.blackbox },
    tour: {
      ...en.tour,
      ...locale.tour,
      steps: locale.tour?.steps ?? en.tour.steps,
    },
    report: { ...en.report, ...locale.report },
    panels: { ...en.panels, ...locale.panels },
    categories: { ...en.categories, ...locale.categories },
    categoryShort: { ...en.categoryShort, ...locale.categoryShort },
    equipment: { ...en.equipment, ...locale.equipment },
    map: { ...en.map, ...locale.map },
    helm: { ...en.helm, ...locale.helm },
  };
}

